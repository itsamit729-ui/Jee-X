def pick(day, subject, ordinal=0):
    pool=[c for c in BANK if c['subject']==subject]
    # Daily shift covers every lesson; the second same-subject slot is half a ring
    # away, so adjacent days cannot repeat even in a four-Reel schedule.
    index=(date.fromisoformat(day).toordinal()+ordinal*(len(pool)//2))%len(pool)
    return dict(pool[index])


def manual(day, ordinal):
    subject=('PHYSICS','CHEMISTRY','MATHS')[ordinal%3]
    pool=[c for c in BANK if c['subject']==subject]
    return dict(pool[(date.fromisoformat(day).toordinal()+ordinal//3)%len(pool)])
